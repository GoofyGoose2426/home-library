-- 4. Clear-cut rough genres carry over as unconfirmed genres (from the shelf
-- photos). Ambiguous ones (Literary & general, Thriller & mystery, Children's
-- & YA…) stay rough until she or a suggestion sets them. Books she has
-- classified herself are skipped.
insert into public.title_tags (owner_id, title_id, tag_id, source, confirmed)
select (select id from owner_ctx), tt.title_id, g.id, 'import', false
from (values
  ('Romance', 'genre', 'Romance'),
  ('Historical romance', 'genre', 'Romance'),
  ('Historical romance', 'subgenre', 'Historical romance'),
  ('Fantasy & paranormal', 'genre', 'Fantasy'),
  ('Sci-fi & speculative', 'genre', 'Sci-fi'),
  ('Classics', 'genre', 'Classics'),
  ('Horror', 'genre', 'Horror'),
  ('Nonfiction', 'genre', 'Nonfiction'),
  ('Poetry', 'genre', 'Poetry')
) as m(rough, kind, name)
join public.tags r on r.kind = 'rough_genre' and r.name = m.rough
join public.title_tags tt on tt.tag_id = r.id
join public.tags g on g.kind = m.kind::public.tag_kind and g.name = m.name
where not exists (select 1 from public.field_sources fs
                  where fs.entity_table = 'titles' and fs.entity_id = tt.title_id
                    and fs.field = 'classification' and fs.source = 'alexandra')
on conflict (title_id, tag_id) do nothing;

